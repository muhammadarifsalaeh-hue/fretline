from playwright.sync_api import sync_playwright, expect
from pathlib import Path
import json,os,re,traceback
OUTPUT=Path(__file__).resolve().parent
BASE=os.environ.get('FRETLINE_QA_URL','http://127.0.0.1:4173')
report={'base_url':BASE,'checks':[],'page_errors':[],'console_errors':[],'failed_requests':[],'expected_faults':[]}
def check(name,value=True):
 report['checks'].append({'name':name,'passed':bool(value)})
 print(name,bool(value),flush=True)
 assert value,name

def cards(page):return page.locator('.catalog-grid article')
def ids(page):return cards(page).evaluate_all('(els)=>els.map(e=>e.dataset.guitarId)')
def visit(page,path):page.goto(BASE+path,wait_until='networkidle')
def read_storage(page,key):return page.evaluate('(key)=>JSON.parse(localStorage.getItem(key)||"[]")','fretline:'+key)

def run():
 with sync_playwright() as p:
  browser=p.chromium.launch(executable_path=os.environ.get('CHROMIUM_BIN','/usr/bin/chromium'),args=['--no-sandbox'])
  page=browser.new_page(viewport={'width':1440,'height':1100})
  page.on('pageerror',lambda error:report['page_errors'].append(str(error)))
  page.on('console',lambda message:report['console_errors'].append(message.text) if message.type=='error' else None)
  page.on('requestfailed',lambda request:report['failed_requests'].append({'url':request.url,'failure':request.failure}))
  visit(page,'/guitars')
  expect(cards(page)).to_have_count(9)
  first_page=ids(page)
  check('Catalog initially displays 9 models',len(first_page)==9)
  check('Five real category controls',page.get_by_role('navigation',name='หมวดหมู่กีตาร์').get_by_role('button').count()==5)
  page.get_by_role('button',name='หน้า 2',exact=True).click();expect(cards(page)).to_have_count(9)
  check('Pagination updates URL and visible models','page=2' in page.url and not set(first_page).intersection(ids(page)))
  page.reload(wait_until='networkidle');check('Pagination survives reload','page=2' in page.url and ids(page)[0]!=first_page[0])
  page.go_back(wait_until='networkidle');check('Browser Back restores first page','page=2' not in page.url and ids(page)==first_page)
  page.locator('#catalog-search').fill('Yamaha');expect(cards(page)).to_have_count(9)
  check('Search filters real catalog',all('yamaha' in value for value in ids(page)))
  page.get_by_role('button',name='หน้า 2',exact=True).click()
  page.locator('#catalog-search').fill('FG830');expect(cards(page)).to_have_count(1)
  check('Changing query resets pagination','page=' not in page.url and ids(page)==['yamaha-fg830'])
  page.locator('#catalog-search').press('Enter');expect(page.locator('.catalog-results')).to_be_focused()
  check('Search form Enter focuses results')
  page.get_by_role('search').get_by_role('button',name='ค้นหา',exact=True).click();expect(page.locator('.catalog-results')).to_be_focused()
  check('Search button focuses results')
  visit(page,'/guitars')
  page.get_by_role('navigation',name='หมวดหมู่กีตาร์').get_by_role('button',name='กีตาร์โปร่ง',exact=True).click()
  check('Category navigation filters acoustic guitars','type=acoustic' in page.url and all('กีตาร์โปร่ง' in text for text in cards(page).all_text_contents()))
  page.get_by_role('navigation',name='หมวดหมู่กีตาร์').get_by_role('button',name='ทั้งหมด',exact=True).click()
  check('All categories clears only the type filter','type=' not in page.url)
  sidebar=page.get_by_role('complementary',name='ตัวกรอง')
  sidebar.get_by_role('searchbox',name='ค้นหาแบรนด์…').fill('tay')
  check('Brand search narrows sidebar choices',sidebar.get_by_role('checkbox').count()==5)
  sidebar.locator('label').filter(has_text='Taylor').click();expect(cards(page)).to_have_count(2)
  check('Brand checkbox filters models',all(value.startswith('taylor-') for value in ids(page)))
  sidebar.get_by_role('searchbox',name='ค้นหาแบรนด์…').fill('nonexistent')
  expect(sidebar.get_by_text('ไม่พบแบรนด์ที่ค้นหา')).to_be_visible();check('Brand search has an empty state')
  visit(page,'/guitars?max=20000&sort=price-asc')
  check('Price filter excludes unknown and over-budget models',0<len(ids(page))<9 and all('สอบถามราคา' not in text for text in cards(page).all_text_contents()))
  prices=cards(page).locator('.catalog-card-price > span:first-child').all_text_contents()
  amounts=[int(re.sub(r'\D','',price)) for price in prices]
  check('Ascending price sort',amounts==sorted(amounts) and max(amounts)<=20000)
  page.get_by_role('combobox',name='เรียงตาม').select_option('price-desc')
  prices=cards(page).locator('.catalog-card-price > span:first-child').all_text_contents()
  amounts=[int(re.sub(r'\D','',price)) for price in prices]
  check('Descending price sort',amounts==sorted(amounts,reverse=True))
  page.get_by_role('combobox',name='เรียงตาม').select_option('name')
  check('Name sorting updates URL','sort=name' in page.url)
  visit(page,'/guitars')
  minimum=page.get_by_role('complementary').get_by_role('slider').nth(0)
  maximum=page.get_by_role('complementary').get_by_role('slider').nth(1)
  minimum.focus();minimum.press('ArrowRight')
  check('Minimum price slider keyboard interaction','min=1000' in page.url)
  maximum.focus();maximum.press('ArrowLeft')
  check('Maximum price slider keyboard interaction','max=' in page.url)
  visit(page,'/guitars?max=0')
  expect(cards(page)).to_have_count(0);check('Zero-price URL is handled without inventing results')
  visit(page,'/guitars?min=garbage&max=Infinity&page=NaN')
  expect(cards(page)).to_have_count(9);check('Invalid numeric URL values fall back safely')
  visit(page,'/guitars?page=999')
  expect(page.get_by_role('button',name='หน้า 4',exact=True)).to_have_attribute('aria-current','page')
  check('Out-of-range page clamps and normalizes','page=4' in page.url)
  visit(page,'/guitars?q=zzzz-no-such-guitar')
  expect(cards(page)).to_have_count(0);expect(page.get_by_text('ไม่พบกีตาร์ที่ตรงกับตัวกรอง')).to_be_visible()
  check('Catalog empty state')
  page.get_by_role('button',name='ล้างตัวกรองทั้งหมด',exact=True).first.click();expect(cards(page)).to_have_count(9)
  check('Clear filters restores results','q=' not in page.url)
  cards(page).first.get_by_role('button',name=re.compile('^บันทึก')).click()
  cards(page).first.get_by_role('button',name=re.compile('^เพิ่ม .*ในการเปรียบเทียบ')).click()
  check('Catalog wishlist and compare actions',len(read_storage(page,'wishlist'))==1 and len(read_storage(page,'compare'))==1)
  page.reload(wait_until='networkidle');check('Wishlist and compare persist',len(read_storage(page,'wishlist'))==1 and len(read_storage(page,'compare'))==1)
  visit(page,'/guitars/fender-american-professional-ii-stratocaster')
  expect(page.get_by_text('ราคาตัวอย่าง · ยังไม่ได้ยืนยัน',exact=True)).to_be_visible()
  check('Sample detail price clearly labelled')
  check('Unverified rating is not presented','★' not in page.locator('.detail-summary').inner_text() and 'reviews' not in page.locator('.detail-summary').inner_text())
  page.get_by_role('tab',name='รีวิว',exact=True).click();expect(page.get_by_text('ยังไม่มีรีวิวที่ตรวจสอบแล้ว',exact=True)).to_be_visible()
  check('Review tab uses honest empty state')
  page.get_by_role('tab',name='สเปก',exact=True).click();expect(page.get_by_role('table')).to_be_visible()
  check('Specifications tab exposes semantic table',page.get_by_role('table').locator('tbody tr').count()>10)
  page.get_by_role('tab',name='สเปก',exact=True).focus();page.keyboard.press('ArrowRight')
  expect(page.get_by_role('tab',name='รีวิว',exact=True)).to_be_focused();check('Detail tabs support Arrow keys')
  page.keyboard.press('Home');expect(page.get_by_role('tab',name='รายละเอียด',exact=True)).to_be_focused()
  check('Detail tabs support Home key')
  check('Similar recommendations exclude current guitar',page.locator('.detail-page .section-y article').count()==4)
  summary=page.locator('.detail-summary')
  summary.get_by_role('button',name='เพิ่มในการเปรียบเทียบแล้ว',exact=True).click()
  check('Detail removes existing comparison',len(read_storage(page,'compare'))==0)
  summary.get_by_role('button',name='เพิ่มในการเปรียบเทียบ',exact=True).click()
  summary.get_by_role('button',name='บันทึกแล้ว',exact=True).click()
  check('Detail wishlist toggles shared storage',len(read_storage(page,'wishlist'))==0)
  visit(page,'/guitars/yamaha-fg830')
  check('Unknown price stays unknown','สอบถามราคา' in page.locator('.detail-price-block').inner_text())
  check('Partial source is linked',page.locator('.detail-source-note a').get_attribute('href').startswith('https://my.yamaha.com/'))
  expect(page.get_by_text('ยังไม่มีรูปถ่ายของรุ่นนี้',exact=False).first).to_be_visible();check('Missing real photos use labelled placeholder')
  check('No fake gallery angles',page.locator('.gallery-thumbnails button').count()==0)
  page.get_by_role('tab',name='สเปก',exact=True).click();check('Unknown specs remain explicitly unknown','ไม่ระบุ' in page.get_by_role('table').inner_text())
  visit(page,'/guitars/not-a-guitar');check('Unknown model preserves 404',page.locator('h1').count()==1 and 'FG830' not in page.locator('h1').inner_text())
  page.evaluate('localStorage.removeItem("fretline:compare");localStorage.removeItem("fretline:wishlist")')
  for label,width,height in [('desktop',1440,1100),('tablet',768,1024),('small-desktop',1024,900),('mobile',390,844),('small-mobile',320,844)]:
   page.set_viewport_size({'width':width,'height':height})
   for kind,path in [('catalog','/guitars'),('detail','/guitars/yamaha-fg830')]:
    visit(page,path)
    check(f'{kind} has no horizontal overflow at {width}px',not page.evaluate('document.documentElement.scrollWidth>innerWidth'))
    if label not in ('small-mobile','small-desktop'):
     page.screenshot(path=str(OUTPUT/f'{kind}-{label}.png'),animations='disabled')
     if label=='desktop':
      if kind=='detail':page.get_by_role('tab',name='สเปก',exact=True).click()
      page.screenshot(path=str(OUTPUT/f'{kind}-desktop-full.png'),full_page=True,animations='disabled')
  page.set_viewport_size({'width':390,'height':844});visit(page,'/guitars')
  opener=page.get_by_role('button',name=re.compile('^ตัวกรอง'));opener.click()
  dialog=page.get_by_role('dialog',name='ตัวกรอง',exact=True);expect(dialog).to_be_visible()
  check('Mobile filter dialog opens')
  dialog.get_by_role('checkbox',name=re.compile('กีตาร์โปร่ง')).press('Space')
  check('Mobile filter uses same URL state','type=acoustic' in page.url)
  focusables=dialog.locator('button').last
  focusables.focus();page.keyboard.press('Tab');expect(dialog.get_by_role('button',name='ปิดตัวกรอง')).to_be_focused()
  check('Mobile filter dialog traps focus')
  page.keyboard.press('Escape');expect(dialog).not_to_be_visible();expect(opener).to_be_focused();check('Mobile filter Escape restores focus')
  page.emulate_media(reduced_motion='reduce');visit(page,'/guitars');check('Reduced motion catalog visible',cards(page).first.evaluate('(el)=>getComputedStyle(el).opacity')=='1')
  page.set_viewport_size({'width':1440,'height':1100});page.emulate_media(reduced_motion='no-preference');visit(page,'/')
  page.screenshot(path=str(OUTPUT/'homepage-regression.png'),animations='disabled')
  check('Homepage headline retained',page.locator('h1').inner_text()=='ค้นพบ\nเสียงที่เป็นคุณ')
  check('No runtime errors during normal interactions',not report['page_errors'])
  check('No console errors during normal interactions',not report['console_errors'])
  check('No failed requests during normal interactions',not report['failed_requests'])
  # Deliberately delay and then reject a lazy route chunk in an isolated context.
  fault=browser.new_page(viewport={'width':1280,'height':900});held=[]
  fault.on('pageerror',lambda error:report['expected_faults'].append(str(error)))
  fault.route('**/assets/CatalogPage-*.js',lambda route:held.append(route))
  fault.goto(BASE+'/guitars',wait_until='domcontentloaded')
  expect(fault.get_by_role('status',name='กำลังโหลดข้อมูลกีตาร์…')).to_be_visible();check('Real lazy loading shows skeleton')
  held[0].abort();expect(fault.get_by_role('alert')).to_be_visible();check('Failed route chunk shows recoverable error state')
  fault.unroute('**/assets/CatalogPage-*.js')
  fault.get_by_role('button',name='ลองใหม่',exact=True).click();expect(fault.get_by_role('heading',name='Catalog',exact=True)).to_be_visible()
  check('Retry reloads route successfully')
  browser.close()

try:
 run()
 report['passed']=True
except Exception:
 report['passed']=False;report['failure']=traceback.format_exc();print(report['failure'],flush=True)
finally:
 (OUTPUT/'results.json').write_text(json.dumps(report,ensure_ascii=False,indent=2))
 print('TOTAL',sum(item['passed'] for item in report['checks']),'/',len(report['checks']),flush=True)
if not report['passed']:raise SystemExit(1)
