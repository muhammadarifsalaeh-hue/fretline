from playwright.sync_api import sync_playwright, expect
from pathlib import Path
import json, os, re, traceback

OUTPUT = Path(__file__).resolve().parent
BASE = os.environ.get('FRETLINE_QA_URL', 'http://127.0.0.1:4185')
report = {'checks': [], 'page_errors': [], 'console_errors': [], 'failed_requests': [], 'screenshots': []}
A = 'yamaha-fg830'
B = 'yamaha-fg820'
C = 'taylor-214ce'
D = 'fender-american-professional-ii-stratocaster'
E = 'gibson-les-paul-standard-60s'

def check(name, condition=True):
    report['checks'].append({'name': name, 'passed': bool(condition)})
    print(name, bool(condition), flush=True)
    assert condition, name

def visit(page, path):
    page.goto(BASE + path, wait_until='networkidle')

def storage(page, key='wishlist'):
    return page.evaluate('(key) => JSON.parse(localStorage.getItem("fretline:" + key) || "[]")', key)

def wait_count(page, n, key='wishlist'):
    page.wait_for_function('({n,key}) => JSON.parse(localStorage.getItem("fretline:"+key)||"[]").length === n', arg={'n': n, 'key': key})

def wishlist_row(page, guitar_id):
    return page.locator(f'.wishlist-row[data-guitar-id="{guitar_id}"]')

def save_screenshot(page, name):
    page.screenshot(path=str(OUTPUT / name), full_page=True, animations='disabled')
    report['screenshots'].append(name)

def run():
    with sync_playwright() as p:
        browser = p.chromium.launch(executable_path=os.environ.get('CHROMIUM_BIN', '/usr/bin/chromium'), args=['--no-sandbox'])
        page = browser.new_page(viewport={'width': 1440, 'height': 1100})
        page.set_default_timeout(10000)
        page.on('pageerror', lambda error: report['page_errors'].append(str(error)))
        page.on('console', lambda message: report['console_errors'].append(message.text) if message.type == 'error' else None)
        page.on('requestfailed', lambda request: report['failed_requests'].append({'url': request.url, 'failure': request.failure}))
        visit(page, '/brands')
        expect(page.get_by_role('heading', name='แบรนด์ทั้งหมด', exact=True)).to_be_visible()
        cards = page.locator('.brand-directory-card')
        all_brands = cards.count()
        counts = page.locator('.brand-card-count').all_text_contents()
        check('All brands are displayed with catalog-derived model counts', all_brands == 11 and sum(int(re.search(r'\d+', value)[0]) for value in counts) == 36)
        check('Unlicensed logos and unsourced brand biographies are absent from cards', cards.locator('img').count() == 0 and not re.search(r'est\.|1946|1887', cards.inner_text() if all_brands == 1 else ' '.join(cards.all_text_contents()), re.I))
        page.get_by_role('searchbox', name='ค้นหาแบรนด์', exact=True).fill(' YaMaHa ')
        expect(cards).to_have_count(1)
        check('Brand search trims whitespace and ignores case', cards.first.get_attribute('data-brand-id') == 'yamaha')
        page.get_by_role('button', name='ล้างคำค้น', exact=True).click()
        expect(cards).to_have_count(all_brands)
        page.get_by_role('group', name='ประเภทกีตาร์', exact=True).get_by_role('button', name='กีตาร์ไฟฟ้า', exact=True).click()
        check('Type filter updates URL and narrows the brand grid', 'type=electric' in page.url and 0 < cards.count() < all_brands)
        page.get_by_role('combobox', name='เรียงตาม', exact=True).select_option('name')
        names = cards.locator('.brand-card-mark').all_text_contents()
        check('Brand name sorting works', names == sorted(names, key=str.lower))
        page.go_back(wait_until='networkidle')
        check('Brand browser Back restores previous sort while retaining filter', 'sort=name' not in page.url and 'type=electric' in page.url)
        page.go_forward(wait_until='networkidle')
        check('Brand browser Forward restores the selected sort', 'sort=name' in page.url)
        page.get_by_role('button', name='ล้างตัวกรอง', exact=True).click()
        page.locator('.brands-extra-filters summary').click()
        page.get_by_role('group', name='ประเทศ (รอยืนยัน)', exact=True).get_by_role('button', name='Japan', exact=True).click()
        check('Existing country filter works and explicitly warns that its metadata is unverified', 'country=Japan' in page.url and cards.count() == 2 and page.get_by_text('ตัวกรองประเทศใช้ข้อมูลเดิม', exact=False).is_visible())
        page.get_by_role('button', name='ล้างตัวกรอง', exact=True).click()
        page.get_by_role('searchbox', name='ค้นหาแบรนด์', exact=True).fill('no-such-fretline-brand')
        expect(page.get_by_role('heading', name='ไม่พบแบรนด์ที่ตรงกัน', exact=True)).to_be_visible()
        check('Brand search empty state appears')
        page.locator('.brands-result-bar').get_by_role('button', name='ล้างตัวกรอง', exact=True).click()
        expect(cards).to_have_count(all_brands)
        check('Clear filters restores the brand grid')
        visit(page, '/brands?type=invalid&country=invalid&sort=invalid')
        check('Invalid brand filters fall back safely', cards.count() == all_brands)
        page.get_by_role('combobox', name='เรียงตาม', exact=True).select_option('price')
        expect(page.get_by_text('ยังไม่มีราคาที่มีแหล่งอ้างอิง', exact=False)).to_be_visible()
        check('Price sorting explains the absence of source-backed prices')
        yamaha_count = int(re.search(r'\d+', page.locator('[data-brand-id="yamaha"] .brand-card-count').inner_text())[0])
        page.locator('[data-brand-id="yamaha"]').click()
        expect(page.locator('h1')).to_have_text('Yamaha')
        guitar_cards = page.locator('.brand-model-grid article')
        check('Brand detail lists exactly that brand catalog count', guitar_cards.count() == yamaha_count)
        check('Every displayed brand-detail card belongs to Yamaha', all('Yamaha' in value for value in guitar_cards.all_text_contents()))
        check('Brand detail does not assert an unsourced history or a sample price', '1887' not in page.locator('main').inner_text() and '24,900' not in page.locator('main').inner_text())
        page.locator('.brand-sources summary').click()
        source_links = page.locator('.brand-sources a').evaluate_all('(links) => links.map(a => ({url:a.href,rel:a.rel}))')
        check('Model sources have recorded dates and safe external links', len(source_links) > 0 and all('yamaha.com/' in link['url'] and 'noopener' in link['rel'] for link in source_links) and '2026-' in page.locator('.brand-sources').inner_text())
        card_a = page.locator(f'.brand-model-grid [data-guitar-id="{A}"]')
        card_a.get_by_role('button', name=re.compile('^บันทึก .*ในรายการโปรด')).click()
        wait_count(page, 1)
        check('Save from Brand Detail updates the shared wishlist', storage(page) == [A])
        card_a.get_by_role('button', name=re.compile('^เพิ่ม .*ในการเปรียบเทียบ')).click()
        wait_count(page, 1, 'compare')
        check('Brand Detail uses the existing compare context', storage(page, 'compare') == [A])
        card_a.get_by_role('link', name='ดูรายละเอียด', exact=True).click()
        expect(page.locator('.detail-summary h1')).to_be_visible()
        check('Brand Detail opens Guitar Detail', '/guitars/' + A in page.url)
        page.go_back(wait_until='networkidle')
        check('Back restores the Brand Detail page', '/brands/yamaha' in page.url)
        visit(page, '/brands/fender?type=classical')
        expect(page.get_by_role('heading', name='ยังไม่มีรุ่นในประเภทนี้', exact=True)).to_be_visible()
        check('Filtered brand collection has a recoverable empty state')
        page.locator('.brand-models-section').get_by_role('button', name='ล้างตัวกรองทั้งหมด', exact=True).click()
        check('Brand Detail clear filter restores its actual models', page.locator('.brand-model-grid article').count() > 0)
        visit(page, '/brands/not-a-real-brand')
        expect(page.locator('h1')).to_have_text('ไม่พบแบรนด์นี้')
        page.get_by_role('link', name='กลับไปดูแบรนด์ทั้งหมด', exact=True).click()
        check('Unknown brand has a useful recovery link', '/brands' in page.url)
        visit(page, '/brands/__proto__')
        expect(page.locator('h1')).to_have_text('ไม่พบแบรนด์นี้')
        check('Inherited-object brand IDs cannot crash the route')
        visit(page, '/wishlist')
        expect(page.locator('.wishlist-row')).to_have_count(1)
        check('Wishlist receives saves from Brand Detail across navigation')
        check('Wishlist uses public price labels without totals', '14,900' not in page.locator('.wishlist-page').inner_text() and 'รวมยอด' in page.locator('.wishlist-page').inner_text())
        visit(page, '/guitars?q=FG820')
        page.locator(f'article[data-guitar-id="{B}"]').get_by_role('button', name=re.compile('^บันทึก .*ในรายการโปรด')).click()
        wait_count(page, 2)
        visit(page, '/guitars/' + C)
        page.locator('.detail-summary').get_by_role('button', name='บันทึกในรายการโปรด', exact=True).click()
        wait_count(page, 3)
        visit(page, '/wishlist')
        check('Catalog and Guitar Detail share the same wishlist', set(storage(page)) == {A, B, C})
        ids = page.locator('.wishlist-row').evaluate_all('(rows)=>rows.map(row=>row.dataset.guitarId)')
        check('Recently saved sorting shows the newest guitar first', ids == [C, B, A])
        page.reload(wait_until='networkidle')
        check('Wishlist survives a page reload', page.locator('.wishlist-row').count() == 3)
        page.get_by_role('combobox', name='เรียงตาม', exact=True).select_option('name')
        check('Wishlist sort is reflected in the URL', 'sort=name' in page.url)
        page.go_back(wait_until='networkidle')
        check('Wishlist browser Back restores recently-saved order', 'sort=name' not in page.url and page.locator('.wishlist-row').first.get_attribute('data-guitar-id') == C)
        page.go_forward(wait_until='networkidle')
        check('Wishlist browser Forward restores name sort', 'sort=name' in page.url)
        page.get_by_role('combobox', name='เรียงตาม', exact=True).select_option('price-desc')
        expect(page.get_by_text('รุ่นที่ยังไม่มีราคาที่มีแหล่งอ้างอิงจะอยู่ท้ายรายการเสมอ', exact=False)).to_be_visible()
        check('Wishlist price sort explains missing and unverified prices')
        wishlist_row(page, C).get_by_role('button', name=re.compile('^เพิ่ม .*ในการเปรียบเทียบ')).click()
        wait_count(page, 2, 'compare')
        check('Individual saved guitar adds to Compare', storage(page, 'compare') == [A, C])
        wishlist_row(page, C).get_by_role('button', name=re.compile('^นำ .*ออกจากการเปรียบเทียบ')).click()
        wait_count(page, 1, 'compare')
        check('Individual comparison toggle removes its guitar')
        page.get_by_role('button', name='เปรียบเทียบ 3 รุ่น', exact=True).click()
        dialog = page.get_by_role('alertdialog')
        expect(dialog).to_be_visible()
        check('Bulk compare asks before replacing the existing selection', storage(page, 'compare') == [A])
        expect(dialog.get_by_role('button', name='ยกเลิก', exact=True)).to_be_focused()
        page.keyboard.press('Shift+Tab')
        expect(dialog.get_by_role('button', name='ใช้รายการนี้', exact=True)).to_be_focused()
        check('Replace dialog traps keyboard focus')
        page.keyboard.press('Escape')
        expect(dialog).not_to_be_visible()
        check('Escape cancels replacement and preserves the comparison', storage(page, 'compare') == [A])
        page.get_by_role('button', name='เปรียบเทียบ 3 รุ่น', exact=True).click()
        dialog.get_by_role('button', name='ใช้รายการนี้', exact=True).click()
        expect(page.get_by_role('table', name='ตารางเปรียบเทียบสเปกกีตาร์')).to_be_visible()
        check('Confirmed bulk compare opens the shared comparison URL', len(storage(page, 'compare')) == 3 and 'ids=' in page.url)
        check('Bulk compare preserves saved favourites', len(storage(page)) == 3)
        visit(page, '/wishlist')
        wishlist_row(page, A).locator('[data-wishlist-detail]').click()
        expect(page.locator('.detail-summary h1')).to_be_visible()
        check('Saved guitar opens its detail page', '/guitars/' + A in page.url)
        page.go_back(wait_until='networkidle')
        remove = wishlist_row(page, C).get_by_role('button', name=re.compile('^นำ .*ออกจากรายการโปรด'))
        remove.focus()
        page.keyboard.press('Enter')
        wait_count(page, 2)
        check('Keyboard removes a saved guitar', C not in storage(page))
        check('Removing a row restores focus to a remaining guitar', page.evaluate('document.activeElement.hasAttribute("data-wishlist-detail")'))
        visit(page, '/guitars/' + C)
        expect(page.locator('.detail-summary').get_by_role('button', name='บันทึกในรายการโปรด', exact=True)).to_have_attribute('aria-pressed', 'false')
        check('Wishlist removal updates the heart on Guitar Detail')
        visit(page, '/wishlist')
        page.get_by_role('button', name='ล้างรายการโปรดทั้งหมด', exact=True).click()
        expect(dialog).to_be_visible()
        dialog.get_by_role('button', name='ยกเลิก', exact=True).click()
        check('Cancel clear keeps all saved guitars', len(storage(page)) == 2)
        page.get_by_role('button', name='ล้างรายการโปรดทั้งหมด', exact=True).click()
        dialog.get_by_role('button', name='ยืนยันล้างรายการ', exact=True).click()
        wait_count(page, 0)
        expect(page.get_by_role('heading', name='ยังไม่มีกีตาร์ในรายการโปรด', exact=True)).to_be_visible()
        expect(page.locator('#wishlist-browse')).to_be_focused()
        check('Confirmed clear shows empty state and restores useful focus')
        expect(page.locator('.phase5-empty-actions a[href="/find-my-guitar"]')).to_be_visible()
        check('Empty wishlist links to the existing quiz')
        visit(page, '/')
        home_card = page.locator('#featured article').first
        if home_card.count() == 0:
            home_card = page.locator('.featured-section article').first
        home_card.get_by_role('button', name=re.compile('^บันทึก .*ในรายการโปรด')).click()
        wait_count(page, 1)
        check('Homepage save integration remains functional')
        visit(page, '/find-my-guitar?type=acoustic&level=beginner&style=folk&budget=mid&priority=versatile')
        expect(page.locator('.match-card').first).to_be_visible()
        result = page.locator('.match-card').filter(has=page.get_by_role('button', name=re.compile('^บันทึก .*ในรายการโปรด'))).first
        result.get_by_role('button', name=re.compile('^บันทึก .*ในรายการโปรด')).click()
        wait_count(page, 2)
        check('Quiz result saves into the same wishlist')
        # Legacy storage migration tests happen on a new document, preserving production data files.
        page.evaluate('({ids})=>{localStorage.setItem("fretline:wishlist",JSON.stringify(ids));localStorage.setItem("fretline:compare","[]")}', {'ids': [A,A,'deleted-model',None,B,C,D,E]})
        visit(page, '/wishlist')
        wait_count(page, 5)
        check('Stored duplicates and deleted IDs are cleaned without losing valid saves', storage(page) == [A,B,C,D,E] and page.locator('.wishlist-row').count() == 5)
        page.get_by_role('button', name='เปรียบเทียบ 4 รุ่นแรก', exact=True).click()
        wait_count(page, 4, 'compare')
        check('Bulk compare enforces four-guitar limit and displayed order', storage(page, 'compare') == [E,D,C,B])
        visit(page, '/wishlist')
        expect(wishlist_row(page, A).locator('.wishlist-compare')).to_be_disabled()
        check('Full comparison disables only unselcted add controls')
        wishlist_row(page, B).locator('.wishlist-compare').click()
        wait_count(page, 3, 'compare')
        expect(wishlist_row(page, A).locator('.wishlist-compare')).to_be_enabled()
        wishlist_row(page, A).locator('.wishlist-compare').click()
        wait_count(page, 4, 'compare')
        check('Removing a selected guitar frees a comparison slot', storage(page, 'compare').count(A) == 1)
        page.evaluate('localStorage.setItem("fretline:wishlist","not-json")')
        page.reload(wait_until='networkidle')
        expect(page.get_by_role('heading', name='ยังไม่มีกีตาร์ในรายการโปรด', exact=True)).to_be_visible()
        check('Invalid stored JSON recovers to an empty wishlist')
        # Capture every developed page at desktop, tablet and mobile dimensions.
        page.evaluate('({ids})=>{localStorage.setItem("fretline:wishlist",JSON.stringify(ids));localStorage.setItem("fretline:compare","[]")}', {'ids':[A,D,C,E]})
        for label,width,height in [('desktop',1440,1100),('tablet',768,1024),('mobile',390,844)]:
            page.set_viewport_size({'width':width,'height':height})
            for slug,path in [('brands','/brands'),('brand-detail','/brands/yamaha'),('wishlist','/wishlist')]:
                visit(page,path)
                expect(page.locator('h1')).to_be_visible()
                check(f'{slug} {label} has no document overflow',page.evaluate('document.documentElement.scrollWidth <= innerWidth + 1'))
                save_screenshot(page,f'{slug}-{label}.png')
            row=wishlist_row(page,C)
            row.get_by_role('button',name=re.compile('^นำ .*ออกจากรายการโปรด')).click()
            wait_count(page,3)
            check(f'Wishlist removal works at {label} width')
            page.evaluate('({ids})=>localStorage.setItem("fretline:wishlist",JSON.stringify(ids))',{'ids':[A,D,C,E]})
        for width in [320,1024]:
            page.set_viewport_size({'width':width,'height':900})
            for path in ['/brands','/brands/fender','/wishlist']:
                visit(page,path)
                check(f'No document overflow at {width}px: {path}',page.evaluate('document.documentElement.scrollWidth <= innerWidth + 1'))
        page.set_viewport_size({'width':390,'height':844})
        page.evaluate('localStorage.setItem("fretline:wishlist","[]")')
        visit(page,'/wishlist')
        save_screenshot(page,'wishlist-empty-mobile.png')
        for path in ['/','/guitars','/guitars/'+A,'/compare?ids='+A+','+B,'/find-my-guitar']:
            visit(page,path)
            expect(page.locator('h1')).to_be_visible()
            check('Phase 1–4 route smoke: '+path, not page.locator('main [role="alert"]').count())
        check('No browser page or runtime errors',not report['page_errors'])
        check('No browser console errors',not report['console_errors'])
        check('No failed page requests',not report['failed_requests'])
        browser.close()

try:
    run()
    report['passed']=True
except Exception:
    report['passed']=False
    report['failure']=traceback.format_exc()
    print(report['failure'],flush=True)
finally:
    (OUTPUT/'browser-results.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
if not report['passed']:
    raise SystemExit(1)
