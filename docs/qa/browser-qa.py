from playwright.sync_api import sync_playwright, expect
import json,re,os
from pathlib import Path
OUTPUT = Path(__file__).resolve().parent
out={'checks':[],'console_errors':[],'page_errors':[],'failed_requests':[]}
def check(name,condition):
 out['checks'].append({'name':name,'passed':bool(condition)})
 print(name, bool(condition),flush=True)
 assert condition,name
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path=os.environ.get('CHROMIUM_BIN', '/usr/bin/chromium'),headless=True,args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1440,'height':1100},device_scale_factor=1)
 page.on('pageerror',lambda e:out['page_errors'].append(str(e)))
 page.on('console',lambda m:out['console_errors'].append(m.text) if m.type=='error' else None)
 page.on('requestfailed',lambda r:out['failed_requests'].append({'url':r.url,'failure':r.failure}))
 base=os.environ.get('FRETLINE_QA_URL', 'http://127.0.0.1:4173')
 page.goto(base,wait_until='networkidle');page.wait_for_timeout(1800)
 check('Thai hero and page title',page.locator('h1').inner_text()=='ค้นพบ\nเสียงที่เป็นคุณ' and 'ค้นพบเสียงที่เป็นคุณ' in page.title())
 check('Local Thai font loaded',page.evaluate('document.fonts.check(\'400 16px Anuphan\')'))
 page.screenshot(path=str(OUTPUT / 'fretline-desktop.png'))
 for y in range(0,page.evaluate('document.body.scrollHeight'),650):
  page.evaluate('(y)=>window.scrollTo(0,y)',y);page.wait_for_timeout(160)
 page.evaluate('window.scrollTo(0,0)');page.wait_for_timeout(900)
 page.screenshot(path=str(OUTPUT / 'fretline-home-full.png'),full_page=True)
 for width in [1440,1024,768,390,320]:
  page.set_viewport_size({'width':width,'height':1000});page.wait_for_timeout(250)
  check(f'Home no horizontal overflow at {width}px',not page.evaluate('document.documentElement.scrollWidth > innerWidth'))
 page.set_viewport_size({'width':1440,'height':1100})
 page.locator('#featured').get_by_role('tab',name='กีตาร์โปร่ง',exact=True).click()
 check('Featured category tab changes cards',page.locator('#featured article').count()>0 and '214ce' in page.locator('#featured article').first.inner_text())
 page.locator('#featured').get_by_role('tab',name='ทั้งหมด',exact=True).click()
 page.get_by_role('button',name='กีตาร์ถัดไป',exact=True).click();page.wait_for_timeout(500)
 check('Featured carousel next scrolls',page.locator('#featured .snap-x').evaluate('(e)=>e.scrollLeft')>0)
 search=page.get_by_role('combobox');search.fill('Yamaha');search.press('ArrowDown')
 check('Autocomplete options and active descendant',page.get_by_role('option').count()>0 and search.get_attribute('aria-activedescendant')=='search-option-0')
 search.press('Escape');check('Escape clears active descendant',search.get_attribute('aria-activedescendant') is None)
 search.press('Enter');page.wait_for_url('**/guitars?q=Yamaha');check('Search submits query after Escape','q=Yamaha' in page.url)
 page.goto(base,wait_until='networkidle');page.wait_for_timeout(1800)
 page.get_by_role('link',name='งบไม่เกิน 20,000 บาท',exact=True).click();check('Budget quick filter','max=20000' in page.url)
 page.goto(base,wait_until='networkidle');page.wait_for_timeout(1800)
 card=page.locator('#featured article').first;card.hover();card.get_by_role('button',name=re.compile('^บันทึก')).click()
 check('Wishlist saved',len(page.evaluate('JSON.parse(localStorage.getItem("fretline:wishlist"))'))==1)
 card.get_by_role('button',name=re.compile('^เพิ่ม .*ในการเปรียบเทียบ')).click()
 card2=page.locator('#featured article').nth(1);card2.hover();card2.get_by_role('button',name=re.compile('^เพิ่ม .*ในการเปรียบเทียบ')).click()
 page.reload(wait_until='networkidle');check('Wishlist and compare survive reload',len(page.evaluate('JSON.parse(localStorage.getItem("fretline:wishlist"))'))==1 and len(page.evaluate('JSON.parse(localStorage.getItem("fretline:compare"))'))==2)
 page.goto(base+'/compare',wait_until='networkidle');check('Comparison table rendered for 2 guitars',page.locator('.compare-table-scroll').count()>0)
 page.get_by_role('switch').click();check('Highlight differences toggle',page.get_by_role('switch').get_attribute('aria-checked')=='true')
 page.goto(base+'/wishlist',wait_until='networkidle');check('Wishlist displays saved guitar',page.locator('article').count()==1)
 for route in ['/guitars','/brands','/brands/yamaha','/find-my-guitar','/guitars/yamaha-fg830','/not-a-page']:
  page.goto(base+route,wait_until='networkidle');check('Route renders '+route,page.locator('h1').count()==1)
 page.goto(base+'/find-my-guitar',wait_until='networkidle');page.get_by_role('button',name='Start the quiz').click()
 for i in range(5):
  group=page.get_by_role('radiogroup');old=group.get_attribute('aria-label');group.locator('label').first.click()
  if i<4:expect(page.get_by_role('radiogroup')).not_to_have_attribute('aria-label',old)
  else:expect(page.get_by_role('radiogroup')).to_have_count(0)
 check('Five-step quiz reaches results',page.locator('article').count()>0)
 page.goto(base+'/compare',wait_until='networkidle');page.locator('header').first.get_by_role('button',name='ค้นหา',exact=True).click();page.wait_for_url('**/#search')
 expect(page.locator('#hero-search')).to_be_focused();check('Navbar search from another page focuses hero',True)
 page.set_viewport_size({'width':390,'height':844});page.goto(base,wait_until='networkidle');page.wait_for_timeout(1800)
 page.screenshot(path=str(OUTPUT / 'fretline-mobile.png'))
 opener=page.get_by_role('button',name='เปิดเมนู',exact=True);opener.click();dialog=page.get_by_role('dialog',name='เมนู',exact=True)
 expect(dialog).to_be_visible();check('Mobile menu opens',opener.get_attribute('aria-expanded')=='true')
 links=dialog.locator('a,button');links.last.focus();page.keyboard.press('Tab');check('Mobile focus loops forward',links.first.evaluate('(e)=>e===document.activeElement'))
 page.keyboard.press('Shift+Tab');check('Mobile focus loops backward',links.last.evaluate('(e)=>e===document.activeElement'))
 page.keyboard.press('Escape');expect(dialog).not_to_be_visible();expect(opener).to_be_focused();check('Escape closes menu and restores focus',True)
 page.goto(base+'/compare',wait_until='networkidle')
 page.get_by_role('navigation',name='เมนูลัด').get_by_role('button',name='ค้นหา',exact=True).click()
 page.wait_for_url('**/#search');expect(page.locator('#hero-search')).to_be_focused()
 check('Mobile bottom search navigates and focuses',True)
 page.emulate_media(reduced_motion='reduce');page.reload(wait_until='networkidle');check('Reduced motion hero remains visible',page.locator('h1').evaluate('(e)=>getComputedStyle(e).opacity')=='1')
 check('No JavaScript page errors',not out['page_errors']);check('No console errors',not out['console_errors']);check('No failed requests',not out['failed_requests'])
 browser.close()
with open(OUTPUT / 'results.json','w') as f:json.dump(out,f,ensure_ascii=False,indent=2)
print(json.dumps(out,ensure_ascii=False,indent=2))
