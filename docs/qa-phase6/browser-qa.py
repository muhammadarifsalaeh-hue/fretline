from playwright.sync_api import sync_playwright, expect
from pathlib import Path
import json, os, re, traceback

OUTPUT = Path(__file__).resolve().parent
BASE = os.environ.get('FRETLINE_QA_URL', 'http://127.0.0.1:4186')
report = {'checks': [], 'page_errors': [], 'console_errors': [], 'failed_requests': [], 'screenshots': []}
PHOTO = 'yamaha-fg820-12'; A = 'yamaha-fg830'; B = 'ibanez-sr300e'; C = 'taylor-gs-mini'; D = 'taylor-214ce'
def check(name, condition=True):
    report['checks'].append({'name': name, 'passed': bool(condition)})
    print(name, bool(condition), flush=True)
    assert condition, name

def visit(page, path):
    page.goto(BASE + path, wait_until='networkidle')

def state(page, key):
    return page.evaluate('(key)=>JSON.parse(localStorage.getItem("fretline:"+key)||"[]")', key)

def count(page, key, n):
    page.wait_for_function('({key,n})=>JSON.parse(localStorage.getItem("fretline:"+key)||"[]").length===n', arg={'key': key, 'n': n})

def shot(page, name):
    page.screenshot(path=str(OUTPUT / name), full_page=True, animations='disabled')
    report['screenshots'].append(name)

def choose(page, value):
    page.locator(f'label.quiz-option:has(input[value="{value}"])').click()

def run():
    with sync_playwright() as p:
        browser = p.chromium.launch(executable_path=os.environ.get('CHROMIUM_BIN', '/usr/bin/chromium'), args=['--no-sandbox'])
        page = browser.new_page(viewport={'width': 1440, 'height': 1100})
        page.set_default_timeout(10000)
        page.on('pageerror', lambda error: report['page_errors'].append(str(error)))
        page.on('console', lambda message: report['console_errors'].append(message.text) if message.type == 'error' else None)
        page.on('requestfailed', lambda request: report['failed_requests'].append({'url': request.url, 'failure': request.failure}))
        visit(page, '/')
        expect(page.locator('h1')).to_be_visible()
        check('Homepage retains its hero and design', 'เสียงที่เป็นคุณ' in page.locator('main').inner_text())
        check('Homepage does not advertise legacy demo price amounts', not re.search(r'฿\s*[0-9][0-9,]*', page.locator('#featured').inner_text()))
        check('Homepage brand cards no longer claim unsourced founding dates', not re.search(r'est\.|1946|1887', page.locator('#brands').inner_text(), re.I))
        page.get_by_role('link', name='มือซ้าย', exact=True).click()
        expect(page.locator('.catalog-grid article')).to_have_count(1)
        check('Existing left-handed quick search finds only the sourced lefty model', page.locator('.catalog-grid article').first.get_attribute('data-guitar-id') == 'yamaha-fg820l')
        visit(page, '/guitars?q=ผู้เริ่มต้น')
        check('Beginner quick search retains manufacturer-positioned models', page.locator('.catalog-grid article').count() >= 2)
        visit(page, '/guitars')
        cards = page.locator('.catalog-grid article')
        expect(cards).to_have_count(9)
        check('Unknown prices do not empty the default catalog', 'ยังไม่มีข้อมูลราคา' in cards.first.inner_text())
        check('No sample status, discounts or review scores appear on catalog cards', 'ข้อมูลตัวอย่าง' not in ' '.join(cards.all_text_contents()) and cards.locator('.line-through').count() == 0 and '★' not in cards.first.inner_text())
        expect(page.get_by_text('ยังไม่มีราคาเงินบาทที่มีแหล่งอ้างอิง', exact=False).first).to_be_visible()
        check('Price controls disclose missing data instead of rendering Infinity', page.locator('.dual-range').count() == 0)
        first = cards.first.get_attribute('data-guitar-id')
        page.get_by_role('button', name='หน้าถัดไป', exact=True).click()
        check('Pagination works with the revised catalog', 'page=2' in page.url and cards.first.get_attribute('data-guitar-id') != first)
        page.go_back(wait_until='networkidle')
        check('Catalog Back restores the first page', cards.first.get_attribute('data-guitar-id') == first)
        visit(page, '/guitars?type=bass&brand=Ibanez')
        expect(cards).to_have_count(1)
        check('Brand and type URL filters intersect correctly', cards.first.get_attribute('data-guitar-id') == B)
        visit(page, '/guitars?sort=name')
        names = cards.locator('h3').all_text_contents()
        check('Catalog name sorting remains functional', len(names) == 9 and cards.first.get_attribute('data-guitar-id') == 'cordoba-c5')
        visit(page, '/guitars?sort=constructor')
        expect(cards).to_have_count(9)
        check('Malformed sort values fall back safely')
        visit(page, '/guitars?max=20000')
        expect(page.get_by_role('heading', name='ยังยืนยันช่วงราคาไม่ได้', exact=True)).to_be_visible()
        check('Budget links explain why no price match can be confirmed')
        page.get_by_role('button', name='ล้างตัวกรองทั้งหมด', exact=True).click()
        expect(cards).to_have_count(9)
        check('Clear budget restores the catalog')
        visit(page, '/guitars?q=FG820')
        card = page.locator(f'article[data-guitar-id="{PHOTO}"]')
        image = card.locator('img')
        expect(image).to_be_visible()
        page.wait_for_function('(selector)=>{const image=document.querySelector(selector);return image&&image.complete&&image.naturalWidth>0}', arg=f'article[data-guitar-id="{PHOTO}"] img')
        check('Real model photo loads on catalog card', image.get_attribute('loading') == 'lazy')
        check('Catalog photo has responsive candidates and intrinsic dimensions', '480w' in image.get_attribute('srcset') and image.get_attribute('width') == '1200' and image.get_attribute('height') == '1600')
        card.get_by_role('button', name=re.compile('^บันทึก .*ในรายการโปรด')).click()
        count(page, 'wishlist', 1)
        card.get_by_role('button', name=re.compile('^เพิ่ม .*ในการเปรียบเทียบ')).click()
        count(page, 'compare', 1)
        card.get_by_role('link', name='ดูรายละเอียด', exact=True).click()
        expect(page.locator('.detail-summary h1')).to_be_visible()
        check('Original photo-model route and ID are retained', '/guitars/' + PHOTO in page.url)
        main_image = page.locator('.gallery-main img')
        expect(main_image).to_be_visible()
        check('Detail photo is eager and responsive', main_image.get_attribute('loading') == 'eager' and '960w' in main_image.get_attribute('srcset'))
        check('Responsive derivatives are not counted as extra gallery angles', page.locator('.gallery-thumbnail').count() == 1)
        credit = page.locator('.guitar-gallery .image-attribution')
        check('Owner-photo caption discloses six fitted strings on a twelve-string guitar', '6 เส้น' in credit.inner_text())
        check('Visible credit links identify author, original source and license', 'Peternick2468' in credit.inner_text() and credit.locator('a[href*="creativecommons.org/licenses/by-sa/4.0"]').count() == 1 and credit.locator('a[href*="commons.wikimedia.org/wiki/File:"]').count() == 1)
        page.locator('.detail-summary .source-scope summary').click()
        scope = page.locator('.detail-summary .source-scope')
        check('Source scope and the supplemental twelve-string evidence are accessible', 'Yamaha FG820-12' in scope.inner_text() and scope.locator('a').count() == 1)
        page.get_by_role('tab', name='สเปก', exact=True).click()
        specs = page.locator('#specs .spec-table')
        check('Real specs retain manufacturer mm and twelve-string count', '634 mm' in specs.inner_text() and specs.get_by_role('row').filter(has_text='12').count() >= 1)
        check('Missing frets and weight are not guessed', 'ไม่ระบุ' in specs.inner_text())
        page.get_by_role('tab', name='รีวิว', exact=True).click()
        check('Reviews remain an honest empty state', 'ยังไม่มีรีวิวที่ตรวจสอบแล้ว' in page.locator('[role="tabpanel"]:visible').inner_text())
        page.locator('.gallery-main').get_by_role('button', name='เปิดดูรูปขนาดใหญ่', exact=True).click()
        dialog = page.get_by_role('dialog', name=re.compile('FG820-12'))
        expect(dialog).to_be_visible()
        check('Lightbox retains visible source and license links', dialog.locator('.image-attribution a').count() == 2)
        dialog.locator('.image-attribution summary').focus()
        page.keyboard.press('Enter')
        check('Transformation disclosure is keyboard accessible in lightbox', dialog.locator('.image-attribution details').get_attribute('open') is not None)
        page.keyboard.press('Escape')
        expect(dialog).not_to_be_visible()
        check('Lightbox Escape restores gallery focus', page.locator('.gallery-main button[aria-label="เปิดดูรูปขนาดใหญ่"]').evaluate('(button)=>button===document.activeElement'))
        visit(page, '/guitars/' + B)
        page.get_by_role('tab', name='สเปก', exact=True).click()
        text = page.locator('#specs .spec-table').inner_text()
        check('SR300E details use current referenced Okoume/Jatoba/PowerSpan specifications', all(value in text for value in ['Okoume','Jatoba','PowerSpan']) and 'Precision + Jazz' not in text)
        page.locator('.detail-summary').get_by_role('button', name='เพิ่มในการเปรียบเทียบ', exact=True).click()
        count(page, 'compare', 2)
        visit(page, '/compare')
        expect(page.get_by_role('table', name='ตารางเปรียบเทียบสเปกกีตาร์')).to_be_visible()
        check('Comparison preserves IDs and new factual values across routes', state(page,'compare') == [PHOTO,B] and 'PowerSpan' in page.locator('main').inner_text())
        check('Comparison has no invented weight or price verdict', 'ราคาต่ำสุดที่มีแหล่งข้อมูล' not in page.locator('main').inner_text() and 'เบาสุดที่มีแหล่งข้อมูล' not in page.locator('main').inner_text() and '★' not in page.locator('main').inner_text())
        visit(page, '/guitars/' + C)
        page.get_by_role('tab', name='สเปก', exact=True).click()
        check('GS Mini Mahogany no longer inherits a spruce-top demo specification', 'mahogany top' in page.locator('#specs').inner_text().lower() and 'spruce' not in page.locator('#specs .spec-table').inner_text().lower())
        visit(page, '/guitars/yamaha-c40')
        page.locator('.detail-summary .source-scope summary').click()
        check('Archived C40 evidence is clearly dated and limited, not conflated with C40II', '2013' in page.locator('.detail-summary .source-scope').inner_text() and '403' in page.locator('.detail-summary .source-scope').inner_text())
        visit(page, '/brands')
        brand_counts = page.locator('.brand-card-count').all_text_contents()
        check('Brand counts still sum to the actual 36-model catalog', sum(int(re.search(r'\d+',x)[0]) for x in brand_counts) == 36)
        page.locator('[data-brand-id="yamaha"]').click()
        check('Brand Detail derives all Yamaha source-backed counts correctly', '21' in page.locator('.brand-detail-stats').inner_text() and '21' in page.locator('.brand-detail-stats > div').nth(2).inner_text())
        brand_photo = page.locator(f'.brand-model-grid [data-guitar-id="{PHOTO}"] img')
        expect(brand_photo).to_be_visible()
        check('Brand Detail uses the same real photo')
        visit(page, '/wishlist')
        expect(page.locator('.wishlist-row')).to_have_count(1)
        expect(page.locator('.wishlist-row img')).to_be_visible()
        check('Wishlist retains the same saved ID, photo and unknown price', state(page,'wishlist') == [PHOTO] and 'ยังไม่มีข้อมูลราคา' in page.locator('.wishlist-row').inner_text())
        page.reload(wait_until='networkidle')
        check('Saved IDs survive reload after data migration', state(page,'wishlist') == [PHOTO])
        page.locator('.wishlist-row').get_by_role('button', name=re.compile('^นำ .*ออกจากรายการโปรด')).click()
        count(page, 'wishlist', 0)
        check('Removing a wishlist item still works after data migration')
        visit(page, '/find-my-guitar')
        page.get_by_role('button', name='เริ่มค้นหากีตาร์', exact=True).click()
        expect(page.get_by_role('button', name='ถัดไป', exact=True)).to_be_disabled()
        check('Quiz prevents advancing with no answer')
        choose(page, 'acoustic'); page.get_by_role('button', name='ถัดไป', exact=True).click()
        choose(page, 'intermediate'); page.get_by_role('button', name='ถัดไป', exact=True).click()
        choose(page, 'folk'); page.get_by_role('button', name='ก่อนหน้า', exact=True).click()
        expect(page.locator('input[value="intermediate"]')).to_be_checked()
        check('Quiz Previous retains an answer')
        page.get_by_role('button', name='ถัดไป', exact=True).click()
        expect(page.locator('input[value="folk"]')).to_be_checked()
        page.get_by_role('button', name='ถัดไป', exact=True).click()
        choose(page, 'mid'); page.get_by_role('button', name='ถัดไป', exact=True).click()
        choose(page, 'versatile'); page.get_by_role('button', name='ดูผลแนะนำ', exact=True).click()
        expect(page.locator('.match-card')).to_have_count(3)
        check('All five quiz steps still return catalog models')
        check('Quiz results show partial data and unknown prices rather than demo amounts', 'ตรวจสอบบางส่วน' in page.locator('.match-card').first.inner_text() and 'ยังไม่มีข้อมูลราคา' in page.locator('.match-card').first.inner_text() and not re.search(r'฿\s*[0-9][0-9,]*',page.locator('.quiz-results-page').inner_text()))
        result = page.locator('.match-card').first
        result.get_by_text('ข้อจำกัดของข้อมูลรุ่นนี้', exact=True).click()
        check('Quiz caveats explain estimated profiles and unknown budgets', 'โปรไฟล์' in result.inner_text() and 'ราคา' in result.inner_text())
        result.get_by_role('button', name=re.compile('^บันทึก .*ในรายการโปรด')).click()
        count(page, 'wishlist', 1)
        check('Quiz results still share wishlist state')
        result.get_by_role('link', name='ดูรายละเอียด', exact=True).click()
        expect(page.locator('.detail-summary h1')).to_be_visible()
        page.go_back(wait_until='networkidle')
        expect(page.locator('.match-card')).to_have_count(3)
        check('Quiz-to-Detail navigation and Browser Back preserve result URLs')
        visit(page, '/image-credits')
        expect(page.locator('h1')).to_have_text('แหล่งที่มาและสิทธิ์ภาพกีตาร์')
        check('Credit page records one genuine licensed image', '1 ภาพ' in page.locator('main').inner_text() and 'CC-BY-SA-4.0' in page.locator('main').inner_text())
        check('Every route exposes the global image-credit link', page.locator('footer a[href="/image-credits"]').count() == 1)
        # Screenshots and no-overflow checks cover every affected route at three widths.
        page.evaluate('localStorage.setItem("fretline:compare","[]");localStorage.setItem("fretline:wishlist",JSON.stringify(["yamaha-fg820-12","ibanez-sr300e"]))')
        paths=[('catalog','/guitars?q=FG820'),('detail','/guitars/'+PHOTO),('compare','/compare?ids='+PHOTO+','+B),('quiz','/find-my-guitar?type=acoustic&level=intermediate&style=folk&budget=mid&priority=versatile'),('brands','/brands/yamaha'),('wishlist','/wishlist'),('credits','/image-credits')]
        for label,width,height in [('desktop',1440,1100),('tablet',768,1024),('mobile',390,844)]:
            page.set_viewport_size({'width':width,'height':height})
            for slug,path in paths:
                visit(page,path)
                expect(page.locator('h1')).to_be_visible()
                check(f'{slug} {label} has no document overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'))
                if slug in ['catalog','detail','compare','wishlist','credits']:
                    shot(page,f'{slug}-{label}.png')
            visit(page,'/guitars/'+PHOTO)
            image=page.locator('.gallery-main img')
            page.wait_for_function('()=>{const image=document.querySelector(".gallery-main img");return image&&image.complete&&image.naturalWidth>0}')
            check(f'Real photo renders at {label} width',image.evaluate('(image)=>image.naturalWidth>0'))
        page.set_viewport_size({'width':320,'height':800})
        for path in ['/guitars/'+PHOTO,'/wishlist','/image-credits']:
            visit(page,path)
            check('320px no overflow: '+path,page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'))
        check('No normal-flow page or runtime errors',not report['page_errors'])
        check('No normal-flow console errors',not report['console_errors'])
        check('No normal-flow failed requests',not report['failed_requests'])
        browser.close()
try:
    run()
    report['passed']=True
except Exception:
    report['passed']=False
    report['failure']=traceback.format_exc()
    print(report['failure'],flush=True)
finally:
    (OUTPUT/'browser-results.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
if not report['passed']:raise SystemExit(1)
