\set ON_ERROR_STOP on
begin;
create function pg_temp.assert_ok(ok boolean,label text) returns void language plpgsql as $$begin
  if ok is distinct from true then raise exception 'FAIL: %',label; end if; raise notice 'PASS: %',label;
end$$;
create function pg_temp.denied(statement text,label text) returns void language plpgsql as $$begin
  begin execute statement; exception when insufficient_privilege then raise notice 'PASS: %',label; return; end;
  raise exception 'FAIL: %',label;
end$$;
create function pg_temp.invalid(statement text,label text) returns void language plpgsql as $$begin
  begin execute statement; exception when raise_exception or serialization_failure or unique_violation or check_violation then raise notice 'PASS: %',label; return; end;
  raise exception 'FAIL: %',label;
end$$;
